export function generatedArtifacts(
  trueDesignMarkdown: string,
  driftReportMarkdown: string,
  extraFiles: Record<string, string> = {},
) {
  return {
    trueDesignMarkdown,
    driftReportMarkdown,
    extraFiles: { ...extraFiles },
    asFiles() {
      return {
        "true-design.md": this.trueDesignMarkdown,
        "document-drift-report.md": this.driftReportMarkdown,
        ...this.extraFiles,
      };
    },
  };
}

export function buildDocumentOverview(inputs: AnalysisInput): [string, Record<string, unknown>] {
  const documentFiles = [...inputs.documentFiles];
  const unsupportedFiles = documentFiles
    .filter(
      (file) => file.content.startsWith("[未対応") || file.content.startsWith("[PDF本文抽出には"),
    )
    .map((file) => file.path);
  const items = {
    document_uris: [...inputs.documentUris],
    document_file_paths: documentFiles.map((file) => file.path),
    unsupported_files: unsupportedFiles,
  };

  const lines = [
    "## ドキュメント事前抽出結果",
    "",
    `- 入力ドキュメントURI数: ${inputs.documentUris.length}`,
    `- 読み込み済み本文ファイル数: ${documentFiles.length}`,
    "",
    "### 入力ドキュメント",
    "",
    ...formatBullets(inputs.documentUris, "入力ドキュメントURIはありません。"),
    "",
    "### 本文抽出ファイル",
    "",
    ...formatDocumentTable(documentFiles),
  ];
  return [lines.join("\n"), items];
}

function formatBullets(values: string[], empty: string): string[] {
  return values.length === 0 ? [empty] : values.map((value) => `- ${value}`);
}

function formatDocumentTable(files: Array<{ path: string; content: string }>): string[] {
  if (files.length === 0) {
    return ["本文抽出済みファイルはありません。"];
  }
  return [
    "| ファイル | 文字数 | 状態 |",
    "| --- | ---: | --- |",
    ...files.map(
      (file) => `| ${file.path} | ${file.content.length} | ${documentStatus(file)} |`,
    ),
  ];
}

function documentStatus(file: { content: string }): string {
  if (file.content.startsWith("[未対応")) {
    return "未対応形式";
  }
  if (file.content.startsWith("[PDF本文抽出には")) {
    return "PDF抽出依存不足";
  }
  if (file.content.startsWith("[") && file.content.includes("抽出できませんでした")) {
    return "抽出不可";
  }
  return "抽出済み";
}

function joinSections(...sections: string[]): string {
  return `${sections
    .map((section) => section.trim())
    .filter(Boolean)
    .join("\n\n")}\n`;
}
